      or v_correction.reason <> v_reason
      or v_correction.corrected_by <> auth.uid() then
      raise exception 'This request identifier was already used for another correction.' using errcode = '23505';
    end if;
    return v_correction.id;
  end if;

  select coalesce(sum(c.quantity)::bigint, 0)
    into v_corrected_quantity
    from public.event_distribution_corrections as c
    where c.distribution_record_id = p_distribution_record_id;
  if p_quantity > v_record.quantity::bigint - v_corrected_quantity then
    raise exception 'A correction cannot exceed the remaining distributed quantity.' using errcode = '22023';
  end if;

  insert into public.event_distribution_corrections (
    request_id, distribution_record_id, event_id, distribution_item_id,
    quantity, reason, corrected_by
  )
  values (
    p_request_id, v_record.id, v_record.event_id, v_record.distribution_item_id,
    p_quantity, v_reason, auth.uid()
  )
  returning * into v_correction;
  return v_correction.id;
end;
$function$;

