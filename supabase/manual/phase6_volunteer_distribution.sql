create or replace function public.record_event_distribution(
  p_event_id bigint,
  p_item_id bigint,
  p_token text,
  p_quantity integer,
  p_request_id uuid
)
returns table (
  record_id uuid,
  quantity_distributed integer,
  participant_quantity bigint,
  item_quantity_distributed bigint,
  inventory_remaining bigint
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_item public.event_distribution_items%rowtype;
  v_eligible record;
  v_locked_ticket record;
  v_record public.event_distribution_records%rowtype;
  v_payment_id uuid;
  v_staff_authorized boolean;
  v_participant_quantity bigint;
  v_item_quantity bigint;
begin
  if auth.uid() is null then
    raise exception 'Sign in to distribute an item.' using errcode = '28000';
  end if;
  if p_quantity is null or p_quantity < 1 or p_request_id is null then
    raise exception 'Enter a positive quantity and retry the request.' using errcode = '22023';
  end if;

  select i.* into v_item
  from public.event_distribution_items as i
  where i.id = p_item_id
    and i.event_id = p_event_id
  for update;
  if not found then
    raise exception 'Distribution item not found for this event.' using errcode = 'P0002';
  end if;

  if not public.evently_ticket_is_super_admin() then
    select true into v_staff_authorized
      from public.user_roles as ur
      join public.event_volunteer_assignments as ev
        on ev.volunteer_user_id = ur.user_id
        and ev.event_id = p_event_id
        and ev.is_active
      join public.event_distribution_item_volunteers as iv
        on iv.event_id = ev.event_id
        and iv.volunteer_user_id = ev.volunteer_user_id
        and iv.distribution_item_id = v_item.id
        and iv.is_active
      where ur.user_id = auth.uid()
        and ur.role::text = 'volunteer'
      limit 1
      for share of ev, iv;
    if not coalesce(v_staff_authorized, false) then
      raise exception 'You are not authorized to distribute this item.' using errcode = '42501';
    end if;
  end if;

  select t.id as ticket_id, r.id as registration_id, r.fee_amount
    into v_locked_ticket
    from public.event_ticket_secrets as secret
    join public.event_tickets as t on t.id = secret.ticket_id
    join public.event_registrations as r on r.id = t.registration_id
    join public.events as e on e.id = t.event_id
    where t.event_id = p_event_id
      and lower(trim(secret.token_secret)) = lower(trim(coalesce(p_token, '')))
      and lower(trim(coalesce(p_token, ''))) ~ '^[0-9a-f]{64}$'
    for share of t, r, e;
  if found then
    if v_locked_ticket.fee_amount > 0 then
      select p.id into v_payment_id
      from public.event_payment_submissions as p
      where p.registration_id = v_locked_ticket.registration_id
      order by p.submitted_at desc, p.id desc
      limit 1
      for share;
    end if;
  end if;

  select eligible.* into v_eligible
  from public.evently_eligible_distribution_registration(p_event_id, p_token) as eligible;
  if not found then
    raise exception 'The ticket is not eligible for this event distribution.' using errcode = '22023';
  end if;

  select r.* into v_record
  from public.event_distribution_records as r
  where r.request_id = p_request_id;
  if found then
    if v_record.distribution_item_id <> p_item_id
      or v_record.event_id <> p_event_id
      or v_record.registration_id <> v_eligible.registration_id
      or v_record.participant_user_id <> v_eligible.participant_user_id
      or v_record.quantity <> p_quantity
      or v_record.distributed_by <> auth.uid() then
      raise exception 'This request identifier was already used for a different distribution.' using errcode = '23505';
    end if;
    select
      coalesce((select sum(r.quantity)::bigint
        from public.event_distribution_records as r
        where r.distribution_item_id = p_item_id
          and r.registration_id = v_eligible.registration_id), 0)
      - coalesce((select sum(c.quantity)::bigint
        from public.event_distribution_corrections as c
        join public.event_distribution_records as r
          on r.id = c.distribution_record_id
        where c.distribution_item_id = p_item_id
          and r.registration_id = v_eligible.registration_id), 0),
      coalesce((select sum(r.quantity)::bigint
        from public.event_distribution_records as r
        where r.distribution_item_id = p_item_id), 0)
      - coalesce((select sum(c.quantity)::bigint
        from public.event_distribution_corrections as c
        where c.distribution_item_id = p_item_id), 0)
      into v_participant_quantity, v_item_quantity;
    return query select v_record.id, v_record.quantity, v_participant_quantity,
      v_item_quantity, greatest(v_item.total_quantity::bigint - v_item_quantity, 0);
    return;
  end if;

  if not v_item.is_active then
    raise exception 'This distribution item is inactive.' using errcode = '22023';
  end if;
  if v_item.distribution_starts_at is not null
    and v_item.distribution_starts_at > clock_timestamp() then
    raise exception 'Distribution for this item has not started.' using errcode = '22023';
  end if;
  if v_item.distribution_ends_at is not null
    and v_item.distribution_ends_at <= clock_timestamp() then
    raise exception 'Distribution for this item has ended.' using errcode = '22023';
  end if;
  if p_quantity > v_item.max_per_participant then
    raise exception 'The requested quantity exceeds the participant limit.' using errcode = '22023';
  end if;

  select
    coalesce((select sum(r.quantity)::bigint
      from public.event_distribution_records as r
      where r.distribution_item_id = p_item_id
        and r.registration_id = v_eligible.registration_id), 0)
    - coalesce((select sum(c.quantity)::bigint
      from public.event_distribution_corrections as c
      join public.event_distribution_records as r
        on r.id = c.distribution_record_id
      where c.distribution_item_id = p_item_id
        and r.registration_id = v_eligible.registration_id), 0),
    coalesce((select sum(r.quantity)::bigint
      from public.event_distribution_records as r
      where r.distribution_item_id = p_item_id), 0)
    - coalesce((select sum(c.quantity)::bigint
      from public.event_distribution_corrections as c
      where c.distribution_item_id = p_item_id), 0)
    into v_participant_quantity, v_item_quantity;

  if v_participant_quantity + p_quantity > v_item.max_per_participant then
    raise exception 'The participant has reached the item quantity limit.' using errcode = '23505';
  end if;
  if v_item_quantity + p_quantity > v_item.total_quantity then
    raise exception 'There is not enough inventory for this distribution.' using errcode = '22023';
  end if;

  insert into public.event_distribution_records (
    request_id, event_id, distribution_item_id,
    event_title_snapshot, item_name_snapshot, registration_id,
    participant_user_id, quantity, distributed_by
  )
  values (
    p_request_id, p_event_id, p_item_id, v_eligible.event_title,
    v_item.item_name, v_eligible.registration_id,
    v_eligible.participant_user_id, p_quantity, auth.uid()
  )
  returning * into v_record;

  return query select v_record.id, v_record.quantity,
    v_participant_quantity + v_record.quantity,
    v_item_quantity + v_record.quantity,
    greatest(v_item.total_quantity::bigint - v_item_quantity - v_record.quantity, 0);
end;
$function$;

