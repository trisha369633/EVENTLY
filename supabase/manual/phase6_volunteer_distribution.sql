create or replace function public.evently_eligible_distribution_registration(
  p_event_id bigint,
  p_token text
)
returns table (
  registration_id bigint,
  participant_user_id uuid,
  participant_name text,
  participant_type text,
  event_title text
)
language sql
stable
security definer
set search_path = ''
as $function$
  select r.id,
    r.user_id,
    r.full_name,
    r.participant_type::text,
    e.title
  from public.event_ticket_secrets as secret
  join public.event_tickets as t on t.id = secret.ticket_id
  join public.event_registrations as r on r.id = t.registration_id
  join public.events as e on e.id = t.event_id
  left join lateral (
    select p.payment_status
    from public.event_payment_submissions as p
    where p.registration_id = r.id
    order by p.submitted_at desc, p.id desc
    limit 1
  ) as payment on true
  where t.event_id = p_event_id
    and lower(trim(secret.token_secret)) = lower(trim(coalesce(p_token, '')))
    and lower(trim(coalesce(p_token, ''))) ~ '^[0-9a-f]{64}$'
    and t.ticket_status = 'active'
    and t.participant_user_id = r.user_id
    and t.event_id = r.event_id
    and r.registration_status::text = 'registered'
    and r.fee_amount >= 0
    and e.status::text not in ('cancelled', 'completed')
    and (r.fee_amount = 0 or payment.payment_status = 'approved')
  limit 1;
$function$;

revoke all on function public.evently_eligible_distribution_registration(bigint, text)
  from public, anon, authenticated;

create or replace function public.evently_revoke_distribution_item_assignments()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if old.is_active and not new.is_active then
    update public.event_distribution_item_volunteers
      set is_active = false,
          revoked_at = clock_timestamp(),
          revoked_by = coalesce(auth.uid(), assigned_by)
