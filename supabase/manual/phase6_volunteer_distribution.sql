    unique (distribution_item_id, volunteer_user_id),
  constraint event_distribution_item_volunteers_revocation_pair
    check ((revoked_at is null) = (revoked_by is null))
);

create index if not exists idx_event_distribution_item_volunteers_active
  on public.event_distribution_item_volunteers
    (volunteer_user_id, event_id, distribution_item_id)
  where is_active;

