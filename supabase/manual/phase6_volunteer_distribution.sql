  revoked_by uuid references public.profiles(id) on delete restrict,
  revoked_at timestamptz,
  constraint event_distribution_item_volunteers_item_event_fk
    foreign key (distribution_item_id, event_id)
    references public.event_distribution_items(id, event_id) on delete cascade,
  constraint event_distribution_item_volunteers_event_assignment_fk
