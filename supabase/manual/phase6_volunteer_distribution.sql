create or replace function public.evently_can_manage_distribution_item(
  p_item_id bigint
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select auth.uid() is not null
    and (
      public.evently_ticket_is_super_admin()
      or exists (
        select 1
        from public.event_distribution_items as i
        join public.event_distribution_item_volunteers as iv
          on iv.distribution_item_id = i.id
          and iv.event_id = i.event_id
          and iv.volunteer_user_id = auth.uid()
          and iv.is_active
        join public.event_volunteer_assignments as ev
          on ev.event_id = i.event_id
          and ev.volunteer_user_id = auth.uid()
          and ev.is_active
        join public.user_roles as ur
          on ur.user_id = auth.uid()
          and ur.role::text = 'volunteer'
        where i.id = p_item_id
      )
    );
$function$;

