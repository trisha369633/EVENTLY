create or replace function public.save_event_distribution_item(
  p_item_id bigint,
  p_event_id bigint,
  p_item_name text,
  p_description text,
  p_total_quantity integer,
  p_max_per_participant integer,
  p_distribution_starts_at timestamptz,
  p_distribution_ends_at timestamptz,
  p_distribution_location text,
  p_is_active boolean
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_item public.event_distribution_items%rowtype;
  v_item_id bigint;
  v_total_distributed bigint;
  v_max_participant_quantity bigint;
  v_name text := trim(coalesce(p_item_name, ''));
begin
  if auth.uid() is null or not public.evently_ticket_is_super_admin() then
    raise exception 'Only a Super Admin can manage distribution items.' using errcode = '42501';
  end if;
  if p_event_id is null
    or not exists (select 1 from public.events as e where e.id = p_event_id) then
    raise exception 'Choose an existing event.' using errcode = '22023';
  end if;
  if length(v_name) not between 1 and 120 then
    raise exception 'Item name must be between 1 and 120 characters.' using errcode = '22023';
  end if;
  if p_description is not null and length(p_description) > 2000 then
    raise exception 'Item description is too long.' using errcode = '22023';
  end if;
  if p_distribution_location is not null
    and length(p_distribution_location) > 240 then
    raise exception 'Distribution location is too long.' using errcode = '22023';
  end if;
  if p_total_quantity is null or p_total_quantity < 0
    or p_max_per_participant is null or p_max_per_participant < 1 then
    raise exception 'Inventory must be zero or more and the participant limit must be positive.' using errcode = '22023';
  end if;
  if p_distribution_starts_at is not null
    and p_distribution_ends_at is not null
    and p_distribution_starts_at >= p_distribution_ends_at then
    raise exception 'The distribution end must be after its start.' using errcode = '22023';
  end if;

  if p_item_id is null then
    insert into public.event_distribution_items (
      event_id, item_name, description, total_quantity,
      max_per_participant, distribution_starts_at, distribution_ends_at,
      distribution_location, is_active, created_by
    )
    values (
      p_event_id, v_name, nullif(trim(coalesce(p_description, '')), ''),
      p_total_quantity, p_max_per_participant,
      p_distribution_starts_at, p_distribution_ends_at,
      nullif(trim(coalesce(p_distribution_location, '')), ''),
      coalesce(p_is_active, true), auth.uid()
    )
    returning id into v_item_id;
    return v_item_id;
  end if;

  select i.* into v_item
  from public.event_distribution_items as i
  where i.id = p_item_id
  for update;
  if not found then
    raise exception 'Distribution item not found.' using errcode = 'P0002';
  end if;

  if v_item.event_id <> p_event_id
    and (
      exists (
        select 1
        from public.event_distribution_records as r
        where r.distribution_item_id = p_item_id
      )
      or exists (
        select 1
        from public.event_distribution_item_volunteers as iv
        where iv.distribution_item_id = p_item_id
      )
    ) then
    raise exception 'An item with distribution history or volunteer access cannot be moved to another event.' using errcode = '22023';
  end if;

  select
    coalesce((select sum(r.quantity) from public.event_distribution_records as r
      where r.distribution_item_id = p_item_id), 0)
    - coalesce((select sum(c.quantity) from public.event_distribution_corrections as c
      where c.distribution_item_id = p_item_id), 0)
    into v_total_distributed;

  with participant_totals as (
    select r.registration_id, sum(r.quantity) as issued_quantity
    from public.event_distribution_records as r
    where r.distribution_item_id = p_item_id
    group by r.registration_id
  ),
  participant_corrections as (
    select r.registration_id, sum(c.quantity) as corrected_quantity
    from public.event_distribution_records as r
    join public.event_distribution_corrections as c
      on c.distribution_record_id = r.id
    where r.distribution_item_id = p_item_id
    group by r.registration_id
  )
  select coalesce(max(t.issued_quantity - coalesce(c.corrected_quantity, 0)), 0)
    into v_max_participant_quantity
    from participant_totals as t
    left join participant_corrections as c using (registration_id);

  if p_total_quantity < v_total_distributed then
    raise exception 'Inventory cannot be reduced below the quantity already distributed.' using errcode = '22023';
  end if;
  if p_max_per_participant < v_max_participant_quantity then
    raise exception 'The participant limit cannot be lower than an existing participant distribution.' using errcode = '22023';
  end if;

  update public.event_distribution_items
    set event_id = p_event_id,
        item_name = v_name,
        description = nullif(trim(coalesce(p_description, '')), ''),
        total_quantity = p_total_quantity,
        max_per_participant = p_max_per_participant,
        distribution_starts_at = p_distribution_starts_at,
        distribution_ends_at = p_distribution_ends_at,
        distribution_location = nullif(trim(coalesce(p_distribution_location, '')), ''),
        is_active = coalesce(p_is_active, false),
        updated_at = clock_timestamp()
    where id = p_item_id
    returning id into v_item_id;
  return v_item_id;
end;
$function$;

