create or replace function public.get_my_distribution_events()
returns table (
  event_id bigint,
  event_title text,
  event_start timestamptz,
  event_status text,
  item_count bigint,
  total_inventory bigint,
  quantity_distributed bigint,
  remaining_inventory bigint,
  pending_items bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
begin
  if auth.uid() is null or not exists (
    select 1 from public.user_roles as ur
    where ur.user_id = auth.uid() and ur.role::text = 'volunteer'
  ) then
    raise exception 'Only volunteers can view the volunteer distribution dashboard.' using errcode = '42501';
  end if;

  return query
    with authorized_items as (
      select distinct i.*
      from public.event_distribution_items as i
      join public.event_distribution_item_volunteers as iv
        on iv.distribution_item_id = i.id
        and iv.event_id = i.event_id
        and iv.volunteer_user_id = auth.uid()
        and iv.is_active
      join public.event_volunteer_assignments as ev
        on ev.event_id = i.event_id
        and ev.volunteer_user_id = auth.uid()
        and ev.is_active
    ),
    item_totals as (
      select i.id,
        coalesce((select sum(r.quantity)::bigint
          from public.event_distribution_records as r
          where r.distribution_item_id = i.id), 0)
        - coalesce((select sum(c.quantity)::bigint
          from public.event_distribution_corrections as c
          where c.distribution_item_id = i.id), 0) as distributed,
        case when i.is_active
          and (i.distribution_starts_at is null or i.distribution_starts_at <= now())
          and (i.distribution_ends_at is null or i.distribution_ends_at > now())
          then true else false end as open_now
      from authorized_items as i
    )
    select i.event_id, e.title, e.event_start, e.status::text,
      count(i.id)::bigint, coalesce(sum(i.total_quantity), 0)::bigint,
      coalesce(sum(t.distributed), 0)::bigint,
      coalesce(sum(greatest(i.total_quantity::bigint - t.distributed, 0)), 0)::bigint,
      count(i.id) filter (
        where t.open_now
          and t.distributed < i.total_quantity
      )::bigint
    from authorized_items as i
    join public.events as e on e.id = i.event_id
    join item_totals as t on t.id = i.id
    group by i.event_id, e.title, e.event_start, e.status
    order by e.event_start desc, e.title;
end;
$function$;

