create or replace function public.get_admin_distribution_summary(
  p_event_id bigint default null
)
returns table (
  events_with_items bigint,
  total_items bigint,
  total_inventory bigint,
  total_distributed bigint,
  remaining_inventory bigint,
  pending_participant_distributions bigint,
  completion_percentage numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
begin
  if auth.uid() is null or not public.evently_ticket_is_super_admin() then
    raise exception 'Only a Super Admin can view distribution analytics.' using errcode = '42501';
  end if;

  return query
    with selected_items as (
      select i.*
      from public.event_distribution_items as i
      where p_event_id is null or i.event_id = p_event_id
    ),
    item_distribution as (
      select i.id,
        coalesce((select sum(r.quantity)::bigint
          from public.event_distribution_records as r
          where r.distribution_item_id = i.id), 0)
        - coalesce((select sum(c.quantity)::bigint
          from public.event_distribution_corrections as c
          where c.distribution_item_id = i.id), 0) as distributed
      from selected_items as i
    ),
    totals as (
      select count(distinct i.event_id)::bigint as event_count,
        count(i.id)::bigint as item_count,
        coalesce(sum(i.total_quantity), 0)::bigint as inventory,
        coalesce(sum(d.distributed), 0)::bigint as distributed,
        coalesce(sum(greatest(i.total_quantity::bigint - d.distributed, 0)), 0)::bigint as remaining
      from selected_items as i
      join item_distribution as d on d.id = i.id
    ),
    eligible_registrations as (
      select r.id as registration_id, r.user_id, r.event_id
      from public.event_registrations as r
      join public.events as e on e.id = r.event_id
      join public.event_tickets as t
        on t.registration_id = r.id
        and t.event_id = r.event_id
        and t.ticket_status = 'active'
      join public.event_ticket_secrets as secret
        on secret.ticket_id = t.id
      left join lateral (
        select p.payment_status
        from public.event_payment_submissions as p
        where p.registration_id = r.id
        order by p.submitted_at desc, p.id desc
        limit 1
      ) as payment on true
      where r.registration_status::text = 'registered'
        and r.fee_amount >= 0
        and e.status::text not in ('cancelled', 'completed')
        and (r.fee_amount = 0 or payment.payment_status = 'approved')
    ),
    pending as (
      select count(*)::bigint as pending_count
      from selected_items as i
      join eligible_registrations as er on er.event_id = i.event_id
      where i.is_active
        and (i.distribution_starts_at is null or i.distribution_starts_at <= now())
        and (i.distribution_ends_at is null or i.distribution_ends_at > now())
        and (
          coalesce((select sum(r.quantity)::bigint
            from public.event_distribution_records as r
            where r.distribution_item_id = i.id
              and r.registration_id = er.registration_id), 0)
          - coalesce((select sum(c.quantity)::bigint
            from public.event_distribution_corrections as c
            join public.event_distribution_records as r
              on r.id = c.distribution_record_id
            where c.distribution_item_id = i.id
              and r.registration_id = er.registration_id), 0)
        ) < i.max_per_participant
        and (
          coalesce((select sum(r.quantity)::bigint
            from public.event_distribution_records as r
            where r.distribution_item_id = i.id), 0)
          - coalesce((select sum(c.quantity)::bigint
            from public.event_distribution_corrections as c
            where c.distribution_item_id = i.id), 0)
        ) < i.total_quantity
    )
    select t.event_count, t.item_count, t.inventory, t.distributed, t.remaining,
      coalesce((select pending_count from pending), 0),
      case when t.inventory = 0 then 0::numeric
        else round((t.distributed::numeric / t.inventory::numeric) * 100, 1)
      end
