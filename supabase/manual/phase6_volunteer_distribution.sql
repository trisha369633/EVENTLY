create or replace function public.get_admin_distribution_items(
  p_event_id bigint default null
)
returns table (
  item_id bigint,
  event_id bigint,
  event_title text,
  item_name text,
  description text,
  total_quantity integer,
  max_per_participant integer,
  distribution_starts_at timestamptz,
  distribution_ends_at timestamptz,
  distribution_location text,
  is_active boolean,
  created_by uuid,
  created_at timestamptz,
  updated_at timestamptz,
  quantity_distributed bigint,
  remaining_inventory bigint,
  active_volunteer_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
begin
  if auth.uid() is null or not public.evently_ticket_is_super_admin() then
    raise exception 'Only a Super Admin can view distribution items.' using errcode = '42501';
  end if;

  return query
    with distribution_totals as (
      select r.distribution_item_id, sum(r.quantity)::bigint as quantity
      from public.event_distribution_records as r
      group by r.distribution_item_id
    ),
    correction_totals as (
      select c.distribution_item_id, sum(c.quantity)::bigint as quantity
      from public.event_distribution_corrections as c
      group by c.distribution_item_id
    ),
    volunteer_totals as (
      select iv.distribution_item_id, count(*)::bigint as volunteer_count
      from public.event_distribution_item_volunteers as iv
      where iv.is_active
      group by iv.distribution_item_id
    )
    select i.id, i.event_id, e.title, i.item_name, i.description,
      i.total_quantity, i.max_per_participant, i.distribution_starts_at,
      i.distribution_ends_at, i.distribution_location, i.is_active,
      i.created_by, i.created_at, i.updated_at,
      coalesce(d.quantity, 0) - coalesce(c.quantity, 0),
      greatest(i.total_quantity::bigint - coalesce(d.quantity, 0)
        + coalesce(c.quantity, 0), 0),
      coalesce(v.volunteer_count, 0)
    from public.event_distribution_items as i
    join public.events as e on e.id = i.event_id
    left join distribution_totals as d on d.distribution_item_id = i.id
    left join correction_totals as c on c.distribution_item_id = i.id
    left join volunteer_totals as v on v.distribution_item_id = i.id
    where p_event_id is null or i.event_id = p_event_id
    order by i.created_at desc, i.id desc;
end;
$function$;

