create or replace function public.get_my_distribution_recent_activity(
  p_limit integer default 10
)
returns table (
  activity_id uuid,
  activity_type text,
  event_id bigint,
  event_title text,
  item_name text,
  participant_name text,
  quantity bigint,
  actor_name text,
  activity_at timestamptz,
  reason text
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
begin
  if auth.uid() is null or not exists (
    select 1 from public.user_roles as ur
    where ur.user_id = auth.uid() and ur.role::text = 'volunteer'
  ) then
    raise exception 'Only volunteers can view volunteer distribution activity.' using errcode = '42501';
  end if;

  return query
    with authorized_items as (
      select distinct i.id, i.event_id
      from public.event_distribution_items as i
      join public.event_distribution_item_volunteers as iv
        on iv.distribution_item_id = i.id
        and iv.event_id = i.event_id
        and iv.volunteer_user_id = auth.uid()
        and iv.is_active
      join public.event_volunteer_assignments as ev
        on ev.event_id = i.event_id
        and ev.volunteer_user_id = auth.uid()
        and ev.is_active
    ),
    activities as (
      select r.id as activity_id, 'distribution'::text as activity_type,
        r.event_id, r.event_title_snapshot as event_title, r.item_name_snapshot as item_name,
        registration.full_name as participant_name, r.quantity::bigint as quantity,
        staff.full_name as actor_name, r.distributed_at as activity_at,
        null::text as reason
      from public.event_distribution_records as r
      join authorized_items as allowed
        on allowed.id = r.distribution_item_id
        and allowed.event_id = r.event_id
      join public.event_distribution_items as i on i.id = r.distribution_item_id
      join public.events as e on e.id = r.event_id
      join public.event_registrations as registration on registration.id = r.registration_id
      join public.profiles as staff on staff.id = r.distributed_by
      union all
      select c.id, 'correction'::text, c.event_id, r.event_title_snapshot, r.item_name_snapshot,
        registration.full_name, -c.quantity::bigint,
        staff.full_name, c.corrected_at, c.reason
      from public.event_distribution_corrections as c
      join authorized_items as allowed
        on allowed.id = c.distribution_item_id
        and allowed.event_id = c.event_id
      join public.event_distribution_records as r
        on r.id = c.distribution_record_id
      join public.event_distribution_items as i on i.id = c.distribution_item_id
      join public.events as e on e.id = c.event_id
      join public.event_registrations as registration on registration.id = r.registration_id
      join public.profiles as staff on staff.id = c.corrected_by
    )
    select a.activity_id, a.activity_type, a.event_id, a.event_title,
      a.item_name, a.participant_name, a.quantity, a.actor_name,
      a.activity_at, a.reason
    from activities as a
    order by a.activity_at desc
    limit greatest(1, least(coalesce(p_limit, 10), 50));
end;
$function$;

