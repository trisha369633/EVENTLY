-- Phase 6 dynamic distribution.
-- Apply phase4_payment_system.sql and phase5_qr_ticket_system.sql first.
-- This migration adds distribution objects and an item-level extension to the
-- existing event_volunteer_assignments permission model. It does not replace
-- ticket validation/check-in or alter registration/payment validation triggers.

begin;

do $phase6_preflight$
begin
  if to_regclass('public.events') is null
    or to_regclass('public.profiles') is null
    or to_regclass('public.user_roles') is null
    or to_regclass('public.event_registrations') is null
    or to_regclass('public.event_payment_submissions') is null
    or to_regclass('public.event_tickets') is null
    or to_regclass('public.event_ticket_secrets') is null
    or to_regclass('public.event_volunteer_assignments') is null then
    raise exception 'Phase 6 requires the Evently Phase 4 payment and Phase 5 ticket/volunteer objects. Apply Phase 4, then Phase 5, before Phase 6.';
  end if;

  if to_regprocedure('public.evently_ticket_is_super_admin()') is null
    or to_regprocedure('public.check_in_event_ticket(bigint,text)') is null then
    raise exception 'Phase 6 requires the existing Phase 5 role and ticket check-in functions.';
  end if;

  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'event_ticket_secrets'
      and column_name = 'token_secret'
  ) or not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'event_payment_submissions'
      and column_name = 'payment_status'
  ) then
    raise exception 'Phase 6 detected an incompatible Phase 4/5 schema. Inspect the installed migrations before proceeding.';
  end if;
end;
$phase6_preflight$;

create table if not exists public.event_distribution_items (
  id bigint generated by default as identity primary key,
  event_id bigint not null
    references public.events(id) on delete cascade,
  item_name text not null
    check (length(trim(item_name)) between 1 and 120),
  description text
    check (description is null or length(description) <= 2000),
  total_quantity integer not null default 0
    check (total_quantity >= 0),
  max_per_participant integer not null default 1
    check (max_per_participant > 0),
  distribution_starts_at timestamptz,
  distribution_ends_at timestamptz,
  distribution_location text
    check (distribution_location is null or length(distribution_location) <= 240),
  is_active boolean not null default true,
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  constraint event_distribution_items_time_order
    check (
      distribution_starts_at is null
      or distribution_ends_at is null
      or distribution_starts_at < distribution_ends_at
    ),
  constraint event_distribution_items_id_event_unique unique (id, event_id)
);

create index if not exists idx_event_distribution_items_event
  on public.event_distribution_items (event_id, is_active, created_at desc);

create table if not exists public.event_distribution_item_volunteers (
