create or replace function public.record_continuous_event_distribution(
  p_event_id bigint,
  p_token text,
  p_item_ids bigint[],
  p_request_id uuid
)
returns table (
  scan_session_id uuid,
  result_code text,
  participant_name text,
  participant_type text,
  item_id bigint,
  item_name text,
  item_status text,
  quantity_distributed integer
)
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_resolved record;
  v_session public.event_distribution_scan_sessions%rowtype;
  v_item public.event_distribution_items%rowtype;
  v_attendee_key text;
  v_item_id bigint;
  v_received bigint;
  v_inventory bigint;
  v_status text;
  v_distributed integer:=0;
  v_selected bigint[];
begin
  if auth.uid() is null then
    raise exception 'Sign in to distribute items.' using errcode='28000';
  end if;
  if p_request_id is null then
    raise exception 'A unique scan request identifier is required.' using errcode='22023';
  end if;
  v_selected:=coalesce(p_item_ids,'{}'::bigint[]);
  if cardinality(v_selected)=0 then
    raise exception 'Select at least one distribution item.' using errcode='22023';
  end if;
  select array_agg(distinct x order by x) into v_selected
  from unnest(v_selected) x;

  select r.* into v_resolved
  from public.evently_resolve_attendee_ticket(p_event_id,p_token) r;
  if not found then
    insert into public.event_distribution_scan_sessions (
      request_id,event_id,distributed_by,selected_item_ids,
      result_code,participant_name_snapshot
    ) values (
      p_request_id,p_event_id,auth.uid(),v_selected,
      'invalid_ticket',null
    ) returning * into v_session;
    insert into public.event_distribution_scan_attempts(
      scan_session_id,status
    ) values(v_session.id,'invalid_ticket');
    return query
      select v_session.id,'invalid_ticket',null::text,null::text,
        null::bigint,null::text,'invalid_ticket',0;
    return;
  end if;

  v_attendee_key:=case
    when v_resolved.attendee_type='guest' then 'guest:'||v_resolved.guest_id::text
    else 'participant:'||v_resolved.registration_id::text
  end;

  insert into public.event_distribution_scan_sessions (
    request_id,event_id,registration_id,attendee_id,participant_user_id,
    participant_name_snapshot,distributed_by,selected_item_ids,result_code
  ) values (
    p_request_id,p_event_id,v_resolved.registration_id,v_resolved.attendee_id,
    (select r.user_id from public.event_registrations r where r.id=v_resolved.registration_id),
    v_resolved.attendee_name,auth.uid(),v_selected,'processing'
  ) returning * into v_session;

  foreach v_item_id in array v_selected
  loop
    v_status:='unavailable';
    select i.* into v_item
    from public.event_distribution_items i
    where i.id=v_item_id and i.event_id=p_event_id
    for update;
    if not found then
      v_status:='unauthorized';
    elsif not public.evently_ticket_is_super_admin()
      and not exists (
        select 1
        from public.event_distribution_item_volunteers iv
        join public.event_volunteer_assignments ev
          on ev.event_id=iv.event_id
          and ev.volunteer_user_id=iv.volunteer_user_id
          and ev.is_active
        where iv.distribution_item_id=v_item.id
          and iv.volunteer_user_id=auth.uid()
          and iv.is_active
      ) then
      v_status:='unauthorized';
    elsif v_resolved.attendee_type='guest'
      and (not coalesce((
        select s.guest_distribution_enabled
        from public.event_guest_settings s
        where s.event_id=p_event_id
      ),false) or not v_item.guest_eligible) then
      v_status:='not_eligible';
    elsif not v_item.is_active then
      v_status:='inactive';
    elsif (v_item.distribution_starts_at is not null and v_item.distribution_starts_at>clock_timestamp())
      or (v_item.distribution_ends_at is not null and v_item.distribution_ends_at<=clock_timestamp()) then
      v_status:='unavailable';
    else
      select coalesce(sum(d.quantity),0) into v_received
      from public.event_distribution_records d
      where d.distribution_item_id=v_item.id
        and d.attendee_id=v_resolved.attendee_id;
      select coalesce(sum(d.quantity),0) into v_inventory
      from public.event_distribution_records d
      where d.distribution_item_id=v_item.id;
      if v_received>=v_item.max_per_participant then
        v_status:='already_received';
      elsif v_inventory>=v_item.total_quantity then
        v_status:='inventory_error';
      else
        begin
          insert into public.event_distribution_records (
            request_id,event_id,distribution_item_id,event_title_snapshot,
            item_name_snapshot,registration_id,participant_user_id,
            quantity,distributed_by,attendee_id,guest_id,attendee_type,attendee_key
          ) values (
            p_request_id,p_event_id,v_item.id,v_resolved.event_title,
            v_item.item_name,v_resolved.registration_id,
            (select r.user_id from public.event_registrations r where r.id=v_resolved.registration_id),
            1,auth.uid(),v_resolved.attendee_id,
            case when v_resolved.attendee_type='guest' then v_resolved.guest_id else null end,
            v_resolved.attendee_type,v_attendee_key
          );
          v_status:='distributed';
          v_distributed:=v_distributed+1;
        exception
          when unique_violation then v_status:='already_received';
          when others then v_status:='inventory_error';
        end;
      end if;
    end if;
    insert into public.event_distribution_scan_attempts(
      scan_session_id,distribution_item_id,item_name_snapshot,status,
      quantity_distributed
    ) values (
      v_session.id,v_item.id,v_item.item_name,v_status,
      case when v_status='distributed' then 1 else 0 end
    );
  end loop;

  update public.event_distribution_scan_sessions
  set result_code=case
    when v_distributed>0 then 'distributed'
    when exists (
      select 1 from public.event_distribution_scan_attempts
      where scan_session_id=v_session.id and status='already_received'
    ) then 'already_received'
    else 'not_distributed'
  end
  where id=v_session.id;

  return query
    select s.id,s.result_code,s.participant_name_snapshot,
      v_resolved.attendee_type,a.distribution_item_id,a.item_name_snapshot,
      a.status,a.quantity_distributed
    from public.event_distribution_scan_sessions s
    join public.event_distribution_scan_attempts a on a.scan_session_id=s.id
    where s.id=v_session.id
    order by a.attempted_at,a.id;
end;
$function$;

