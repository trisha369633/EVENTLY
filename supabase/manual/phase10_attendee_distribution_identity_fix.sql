create or replace function public.get_admin_distribution_history(
  p_event_id bigint default null,
  p_item_id bigint default null,
  p_volunteer_user_id uuid default null,
  p_status text default null,
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  activity_id uuid,
  activity_type text,
  event_id bigint,
  event_title text,
  item_id bigint,
  item_name text,
  registration_id bigint,
  attendee_id bigint,
  attendee_name text,
  attendee_type text,
  relationship text,
  ticket_reference text,
  participant_name text,
  participant_type text,
  quantity bigint,
  net_quantity bigint,
  actor_user_id uuid,
  actor_name text,
  activity_at timestamptz,
  activity_status text,
  reason text,
  request_id uuid
)
language plpgsql
stable
security definer
set search_path=''
as $function$
begin
  if auth.uid() is null or not public.evently_ticket_is_super_admin() then
    raise exception 'Only a Super Admin can view distribution history.' using errcode='42501';
  end if;

  return query
  with corrected as (
    select c.distribution_record_id,sum(c.quantity)::bigint quantity
    from public.event_distribution_corrections c
    group by c.distribution_record_id
  ),
  activities(activity_id,activity_type,event_id,event_title,item_id,item_name,
    registration_id,attendee_id,attendee_name,attendee_type,relationship,
    ticket_reference,participant_name,participant_type,quantity,net_quantity,
    actor_user_id,actor_name,activity_at,activity_status,reason,request_id) as (
    select d.id,'distribution'::text,d.event_id,d.event_title_snapshot,
      i.id,d.item_name_snapshot,d.registration_id,a.id,
      coalesce(a.attendee_name_snapshot,r.full_name),
      coalesce(d.attendee_type,a.attendee_type),
      a.relationship_snapshot,t.ticket_reference,
      r.full_name,r.participant_type::text,d.quantity,
      d.quantity-coalesce(cr.quantity,0),
      d.distributed_by,p.full_name,d.distributed_at,
      case
        when coalesce(cr.quantity,0)>=d.quantity then 'corrected'
        when coalesce(cr.quantity,0)>0 then 'partially_corrected'
        else 'distributed'
      end::text,null::text,d.request_id
    from public.event_distribution_records d
    join public.event_distribution_items i on i.id=d.distribution_item_id
    join public.event_registrations r on r.id=d.registration_id
    left join public.event_attendees a on a.id=d.attendee_id
    left join public.event_tickets t on t.attendee_id=a.id
    join public.profiles p on p.id=d.distributed_by
    left join corrected cr on cr.distribution_record_id=d.id
    where (p_event_id is null or d.event_id=p_event_id)
      and (p_item_id is null or d.distribution_item_id=p_item_id)
      and (p_volunteer_user_id is null or d.distributed_by=p_volunteer_user_id)
      and (
        coalesce(p_status,'all') in ('','all')
        or (p_status='distributed' and d.quantity>coalesce(cr.quantity,0))
        or (p_status='corrected' and coalesce(cr.quantity,0)>0)
      )
    union all
    select c.id,'correction'::text,c.event_id,d.event_title_snapshot,
      i.id,d.item_name_snapshot,d.registration_id,a.id,
      coalesce(a.attendee_name_snapshot,r.full_name),
      coalesce(d.attendee_type,a.attendee_type),
      a.relationship_snapshot,t.ticket_reference,
      r.full_name,r.participant_type::text,-c.quantity,
      d.quantity-coalesce(cr.quantity,0),
      c.corrected_by,p.full_name,c.corrected_at,
      'corrected'::text,c.reason,c.request_id
    from public.event_distribution_corrections c
    join public.event_distribution_records d on d.id=c.distribution_record_id
    join public.event_distribution_items i on i.id=d.distribution_item_id
    join public.event_registrations r on r.id=d.registration_id
    left join public.event_attendees a on a.id=d.attendee_id
    left join public.event_tickets t on t.attendee_id=a.id
    join public.profiles p on p.id=c.corrected_by
    left join corrected cr on cr.distribution_record_id=d.id
    where (p_event_id is null or c.event_id=p_event_id)
      and (p_item_id is null or c.distribution_item_id=p_item_id)
      and (p_volunteer_user_id is null or c.corrected_by=p_volunteer_user_id)
      and coalesce(p_status,'all') in ('','all','corrected')
  )
  select x.*
  from activities x
  order by x.activity_at desc
  limit greatest(1,least(coalesce(p_limit,50),100))
  offset greatest(coalesce(p_offset,0),0);
end;
$function$;

