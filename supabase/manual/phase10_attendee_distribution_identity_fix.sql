begin
  if to_regclass('public.events') is null
    or to_regclass('public.event_registrations') is null
    or to_regclass('public.event_guests') is null
    or to_regclass('public.event_tickets') is null
    or to_regclass('public.event_ticket_secrets') is null
    or to_regclass('public.event_distribution_items') is null
    or to_regclass('public.event_distribution_records') is null
    or to_regclass('public.event_distribution_corrections') is null
    or to_regprocedure('public.validate_attendee_ticket(bigint,text)') is null
    or to_regprocedure('public.record_continuous_attendee_distribution(bigint,text,bigint[],uuid)') is null
  then
    raise exception 'Phase 10 attendee fix requires phases 3-10, including event_guests, attendee ticket validation, and continuous attendee distribution.';
  end if;

  if not exists (
    select 1
    from information_schema.columns
    where table_schema='public' and table_name='event_tickets'
      and column_name='attendee_key'
  ) or not exists (
    select 1
    from information_schema.columns
    where table_schema='public' and table_name='event_distribution_records'
      and column_name='attendee_key'
  ) then
    raise exception 'Phase 10 attendee fix requires attendee_key columns from phase10_guest_registration.sql.';
  end if;
end;
