-- Keep existing ticket references intact. Only newly issued main-participant
-- tickets receive the stable registration-P reference format.
create or replace function public.evently_issue_event_ticket(p_registration_id bigint)
returns table (
  ticket_id uuid,
  ticket_reference text,
  ticket_token text,
  ticket_status text,
  issued_at timestamptz,
  checked_in_at timestamptz
)
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_registration public.event_registrations%rowtype;
  v_attendee public.event_attendees%rowtype;
  v_event_status text;
  v_payment_status text;
  v_ticket_id uuid;
  v_ticket_reference text;
  v_ticket_token text;
  v_ticket_status text;
  v_issued_at timestamptz;
  v_checked_in_at timestamptz;
begin
  select r.* into v_registration
  from public.event_registrations r
  where r.id=p_registration_id
  for update;
  if not found
    or v_registration.registration_status::text<> 'registered'
    or v_registration.fee_amount is null
    or v_registration.fee_amount<0 then
    return;
  end if;

  select e.status::text into v_event_status
  from public.events e
  where e.id=v_registration.event_id;
  if not found or v_event_status in ('cancelled','completed') then
    return;
  end if;

  if v_registration.fee_amount>0 then
    select p.payment_status into v_payment_status
    from public.event_payment_submissions p
    where p.registration_id=v_registration.id
    order by p.submitted_at desc,p.id desc
    limit 1;
    if v_payment_status is distinct from 'approved' then
      return;
    end if;
  end if;

  insert into public.event_attendees (
    event_id,registration_id,attendee_type,guest_id,
    attendee_name_snapshot,relationship_snapshot,attendee_key
  )
  values (
    v_registration.event_id,v_registration.id,'participant',null,
    v_registration.full_name,null,'participant:'||v_registration.id::text
  )
  on conflict (attendee_key) do update
  set attendee_name_snapshot=excluded.attendee_name_snapshot
  returning * into v_attendee;

  select t.id,t.ticket_reference,t.ticket_status,t.issued_at,t.checked_in_at
  into v_ticket_id,v_ticket_reference,v_ticket_status,v_issued_at,v_checked_in_at
  from public.event_tickets t
  where t.attendee_id=v_attendee.id
     or (t.attendee_type='participant' and t.registration_id=v_registration.id)
  order by t.issued_at desc
  for update
  limit 1;
  if found then
    update public.event_tickets
    set attendee_id=v_attendee.id,
        attendee_type='participant',
        attendee_name_snapshot=v_registration.full_name,
        attendee_key=v_attendee.attendee_key
    where id=v_ticket_id;
    select s.token_secret into v_ticket_token
    from public.event_ticket_secrets s
    where s.ticket_id=v_ticket_id;
    return query
      select v_ticket_id,v_ticket_reference,v_ticket_token,v_ticket_status,
        v_issued_at,v_checked_in_at;
    return;
  end if;

  v_ticket_token := lower(
    replace(gen_random_uuid()::text,'-','')
    || replace(gen_random_uuid()::text,'-','')
  );
  v_ticket_reference := 'EVT-'||v_registration.id::text||'-P';
  while exists (
    select 1 from public.event_tickets
    where ticket_reference=v_ticket_reference
  ) loop
    v_ticket_reference := 'EVT-'||v_registration.id::text||'-P-'||
      upper(replace(gen_random_uuid()::text,'-',''));
  end loop;

  insert into public.event_tickets (
    registration_id,event_id,participant_user_id,ticket_reference,
    attendee_type,attendee_id,guest_id,attendee_name_snapshot,
    relationship_snapshot,attendee_key
  )
  values (
    v_registration.id,v_registration.event_id,v_registration.user_id,
    v_ticket_reference,'participant',v_attendee.id,null,
    v_registration.full_name,null,v_attendee.attendee_key
  )
  returning id,ticket_status,issued_at,checked_in_at
  into v_ticket_id,v_ticket_status,v_issued_at,v_checked_in_at;
  insert into public.event_ticket_secrets(ticket_id,token_secret)
  values(v_ticket_id,v_ticket_token);
  return query
    select v_ticket_id,v_ticket_reference,v_ticket_token,v_ticket_status,
      v_issued_at,v_checked_in_at;
end;
$function$;

