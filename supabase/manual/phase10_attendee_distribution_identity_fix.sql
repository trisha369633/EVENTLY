create or replace function public.evently_resolve_attendee_ticket(
  p_event_id bigint,
  p_token text
)
returns table (
  ticket_id uuid,
  attendee_id bigint,
  attendee_type text,
  guest_id bigint,
  guest_relationship text,
  registration_id bigint,
  attendee_name text,
  participant_type text,
  event_id bigint,
  event_title text,
  ticket_reference text,
  ticket_status text,
  checked_in_at timestamptz,
  ticket_valid boolean
)
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_ticket record;
begin
  if auth.uid() is null then
    raise exception 'Sign in to resolve tickets.' using errcode='28000';
  end if;
  if not public.evently_ticket_is_super_admin()
    and not exists (
      select 1
      from public.event_volunteer_assignments a
      where a.event_id=p_event_id
        and a.volunteer_user_id=auth.uid()
        and a.is_active
    ) then
    raise exception 'You are not assigned to validate tickets for this event.' using errcode='42501';
  end if;

  select t.*, r.full_name as main_name, r.participant_type::text as participant_type,
    r.registration_status, r.fee_amount, g.status as guest_status,
    g.relationship as guest_relationship, e.title as event_title, e.status::text as event_status
  into v_ticket
  from public.event_ticket_secrets s
  join public.event_tickets t on t.id=s.ticket_id
  join public.event_registrations r on r.id=t.registration_id
  join public.events e on e.id=t.event_id
  left join public.event_guests g on g.id=t.guest_id
  where t.event_id=p_event_id
    and lower(trim(s.token_secret))=lower(trim(coalesce(p_token,'')))
    and lower(trim(coalesce(p_token,''))) ~ '^[0-9a-f]{64}$';

  if not found
    or v_ticket.ticket_status <> 'active'
    or v_ticket.registration_status <> 'registered'
    or v_ticket.event_status in ('cancelled','completed')
    or (v_ticket.attendee_type='guest' and v_ticket.guest_status <> 'registered')
  then
    return;
  end if;

  if v_ticket.fee_amount>0 and not exists (
    select 1
    from public.event_payment_submissions ps
    where ps.registration_id=v_ticket.registration_id
      and ps.payment_status='approved'
  ) then
    return;
  end if;

  return query
  select v_ticket.id, v_ticket.attendee_id, v_ticket.attendee_type,
    v_ticket.guest_id, v_ticket.guest_relationship,
    v_ticket.registration_id,
    coalesce(v_ticket.attendee_name_snapshot,v_ticket.main_name),
    v_ticket.participant_type, v_ticket.event_id, v_ticket.event_title,
    v_ticket.ticket_reference, v_ticket.ticket_status,
    v_ticket.checked_in_at, true;
end;
$function$;

