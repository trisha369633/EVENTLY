create or replace function public.get_my_event_distribution_benefits(
  p_event_id bigint default null
)
returns table (
  event_id bigint,
  event_title text,
  registration_id bigint,
  attendee_id bigint,
  attendee_type text,
  attendee_name text,
  relationship text,
  ticket_reference text,
  checked_in_at timestamptz,
  item_id bigint,
  item_name text,
  description text,
  status text,
  quantity_received bigint,
  distributed_at timestamptz
)
language plpgsql
stable
security definer
set search_path=''
as $function$
begin
  if auth.uid() is null then
    raise exception 'Sign in to view event benefits.' using errcode='28000';
  end if;

  return query
  select i.event_id,e.title,a.registration_id,a.id,a.attendee_type,
    a.attendee_name_snapshot,a.relationship_snapshot,
    t.ticket_reference,t.checked_in_at,i.id,i.item_name,i.description,
    case when coalesce(received.quantity_received,0)>0
      then 'received' else 'not_received' end::text,
    coalesce(received.quantity_received,0)::bigint,
    received.last_distributed_at
  from public.event_attendees a
  join public.event_registrations r on r.id=a.registration_id
  join public.events e on e.id=a.event_id
  join public.event_distribution_items i on i.event_id=a.event_id
  left join public.event_tickets t
    on t.attendee_id=a.id
    and t.ticket_status='active'
  left join lateral (
    select
      greatest(
        coalesce(sum(d.quantity),0)
        - coalesce((
          select sum(c.quantity)
          from public.event_distribution_corrections c
          join public.event_distribution_records cr on cr.id=c.distribution_record_id
          where cr.attendee_id=a.id
            and cr.distribution_item_id=i.id
        ),0),
        0
      )::bigint as quantity_received,
      max(d.distributed_at) as last_distributed_at
    from public.event_distribution_records d
    where d.attendee_id=a.id
      and d.distribution_item_id=i.id
  ) received on true
  where r.user_id=auth.uid()
    and r.registration_status::text='registered'
    and (p_event_id is null or a.event_id=p_event_id)
    and i.is_active
  order by e.title,a.attendee_type,a.attendee_name_snapshot,i.item_name;
end;
