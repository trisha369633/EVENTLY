create or replace function public.record_continuous_attendee_distribution(
  p_event_id bigint,
  p_token text,
  p_item_ids bigint[],
  p_request_id uuid
)
returns table (
  attendee_type text,
  attendee_name text,
  relationship text,
  main_participant_name text,
  item_id bigint,
  item_name text,
  item_status text,
  quantity_distributed integer
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_ticket record;
  v_item public.event_distribution_items%rowtype;
  v_selected bigint;
  v_attendee_key text;
  v_participant_quantity bigint;
  v_item_quantity bigint;
  v_status text;
  v_request public.event_attendee_distribution_requests%rowtype;
  v_selected_keys bigint[];
  v_result jsonb := '[]'::jsonb;
  v_guest_distribution_enabled boolean;
begin
  if auth.uid() is null then
    raise exception 'Sign in to distribute items.' using errcode='28000';
  end if;
  if p_request_id is null then
    raise exception 'A unique scan request identifier is required.' using errcode='22023';
  end if;
  if cardinality(coalesce(p_item_ids,'{}'::bigint[])) = 0 then
    raise exception 'Select at least one distribution item.' using errcode='22023';
  end if;
  select array_agg(distinct item_id order by item_id)
  into v_selected_keys
  from unnest(p_item_ids) as item_id;
  select s.guest_distribution_enabled
  into v_guest_distribution_enabled
  from public.event_guest_settings as s
  where s.event_id = p_event_id;

  select t.*, r.full_name as main_name, r.registration_status,
    r.fee_amount, g.full_name as guest_name, g.relationship as guest_relationship,
    g.status as guest_status, g.id as resolved_guest_id
  into v_ticket
  from public.event_ticket_secrets as s
  join public.event_tickets as t on t.id=s.ticket_id
  join public.event_registrations as r on r.id=t.registration_id
  left join public.event_guests as g on g.id=t.guest_id
  where t.event_id=p_event_id
    and lower(trim(s.token_secret))=lower(trim(coalesce(p_token,'')))
    and lower(trim(coalesce(p_token,''))) ~ '^[0-9a-f]{64}$'
  for update of t;

  if not found
    or v_ticket.ticket_status <> 'active'
    or v_ticket.registration_status <> 'registered'
    or (v_ticket.attendee_type='guest' and v_ticket.guest_status <> 'registered')
  then
    return query
      select 'guest'::text,'Invalid attendee'::text,null::text,null::text,
        null::bigint,null::text,'invalid_ticket'::text,0;
    return;
  end if;

  if v_ticket.fee_amount > 0 and not exists (
    select 1
    from public.event_payment_submissions as p
    where p.registration_id=v_ticket.registration_id
      and p.payment_status='approved'
  ) then
    return query
      select v_ticket.attendee_type::text,
        coalesce(v_ticket.attendee_name_snapshot,v_ticket.main_name)::text,
        v_ticket.relationship_snapshot,
        v_ticket.main_name::text,
        null::bigint,null::text,'invalid_ticket'::text,0;
    return;
  end if;

  v_attendee_key := case
    when v_ticket.attendee_type='guest' then 'guest:'||v_ticket.resolved_guest_id::text
    else 'participant:'||v_ticket.registration_id::text
  end;

  select r.* into v_request
  from public.event_attendee_distribution_requests as r
  where r.request_id=p_request_id
  for update;
  if found then
    if v_request.event_id <> p_event_id
      or v_request.attendee_key <> v_attendee_key
      or v_request.distributed_by <> auth.uid()
      or v_request.selected_item_ids <> v_selected_keys
    then
      raise exception 'This request identifier was already used for a different scan.'
        using errcode='23505';
    end if;
    return query
      select
        (row->>'attendee_type')::text,
        (row->>'attendee_name')::text,
        (row->>'relationship')::text,
        (row->>'main_participant_name')::text,
        nullif(row->>'item_id','')::bigint,
        (row->>'item_name')::text,
        (row->>'item_status')::text,
        coalesce((row->>'quantity_distributed')::integer,0)
      from jsonb_array_elements(v_request.result_json) as row;
    return;
  end if;

  foreach v_selected in array p_item_ids
  loop
    v_status := 'unavailable';
    select i.* into v_item
    from public.event_distribution_items as i
    where i.id=v_selected
      and i.event_id=p_event_id
    for update;

    if not found then
      v_status := 'unauthorized';
    elsif not public.evently_ticket_is_super_admin()
      and not exists (
        select 1
        from public.event_volunteer_assignments as ev
        join public.event_distribution_item_volunteers as iv
          on iv.event_id=ev.event_id
          and iv.volunteer_user_id=ev.volunteer_user_id
          and iv.distribution_item_id=v_item.id
          and iv.is_active
        join public.user_roles as ur
          on ur.user_id=ev.volunteer_user_id
          and ur.role::text='volunteer'
        where ev.event_id=p_event_id
          and ev.volunteer_user_id=auth.uid()
          and ev.is_active
      )
    then
      v_status := 'unauthorized';
    elsif v_ticket.attendee_type='guest'
      and (coalesce(v_guest_distribution_enabled,false) = false
        or not v_item.guest_eligible) then
      v_status := 'not_eligible';
    elsif not v_item.is_active then
      v_status := 'inactive';
    elsif v_item.distribution_starts_at is not null
      and v_item.distribution_starts_at > clock_timestamp()
      or v_item.distribution_ends_at is not null
      and v_item.distribution_ends_at <= clock_timestamp()
    then
      v_status := 'unavailable';
    else
      select
        coalesce(sum(r.quantity) filter (
          where r.attendee_key=v_attendee_key
        ),0)::bigint,
        coalesce(sum(r.quantity),0)::bigint
      into v_participant_quantity,v_item_quantity
      from public.event_distribution_records as r
      where r.distribution_item_id=v_item.id;

      if v_participant_quantity >= v_item.max_per_participant then
        v_status := 'already_received';
      elsif v_item_quantity >= v_item.total_quantity then
        v_status := 'inventory_error';
      else
        begin
          insert into public.event_distribution_records (
            request_id,event_id,distribution_item_id,event_title_snapshot,
            item_name_snapshot,registration_id,participant_user_id,
            quantity,distributed_by,guest_id,attendee_type,attendee_key
          )
          values (
            gen_random_uuid(),p_event_id,v_item.id,
            (select title from public.events where id=p_event_id),
            v_item.item_name,v_ticket.registration_id,v_ticket.participant_user_id,
            1,auth.uid(),
            case when v_ticket.attendee_type='guest' then v_ticket.resolved_guest_id else null end,
            v_ticket.attendee_type,v_attendee_key
          );
          v_status := 'distributed';
        exception
          when unique_violation then
            v_status := 'already_received';
          when others then
            v_status := 'inventory_error';
        end;
      end if;
    end if;

    v_result := v_result || jsonb_build_array(jsonb_build_object(
      'attendee_type', v_ticket.attendee_type,
      'attendee_name', coalesce(v_ticket.attendee_name_snapshot,v_ticket.guest_name,v_ticket.main_name),
      'relationship', v_ticket.relationship_snapshot,
      'main_participant_name', v_ticket.main_name,
      'item_id', v_item.id,
      'item_name', v_item.item_name,
      'item_status', v_status,
      'quantity_distributed', case when v_status='distributed' then 1 else 0 end
    ));

    return query
      select v_ticket.attendee_type::text,
        coalesce(v_ticket.attendee_name_snapshot,v_ticket.guest_name,v_ticket.main_name)::text,
        v_ticket.relationship_snapshot,
        v_ticket.main_name::text,
        v_item.id,
        v_item.item_name,
        v_status::text,
        case when v_status='distributed' then 1 else 0 end;
  end loop;

  insert into public.event_attendee_distribution_requests (
    request_id, event_id, attendee_key, selected_item_ids,
    distributed_by, result_json
  ) values (
    p_request_id, p_event_id, v_attendee_key, v_selected_keys,
    auth.uid(), v_result
  );
end;
$function$;

