create or replace function public.check_in_attendee_ticket(
  p_event_id bigint,
  p_token text
)
returns table (
  result_code text,
  result_message text,
  attendee_type text,
  attendee_name text,
  relationship text,
  main_participant_name text,
  event_title text,
  ticket_reference text,
  checked_in_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_ticket_id uuid;
  v_ticket_reference text;
  v_checked timestamptz;
begin
  if auth.uid() is null then
    raise exception 'Sign in to check in tickets.' using errcode = '28000';
  end if;

  select v.ticket_reference
  into v_ticket_reference
  from public.validate_attendee_ticket(p_event_id,p_token) as v
  limit 1;

  if v_ticket_reference is null then
    return query select 'INVALID'::text, 'The ticket is invalid, revoked, cancelled, unpaid, or ineligible.'::text,
      null::text,null::text,null::text,null::text,null::text,null::text,null::timestamptz;
    return;
  end if;

  select t.id, t.checked_in_at
  into v_ticket_id, v_checked
  from public.event_ticket_secrets as s
  join public.event_tickets as t on t.id=s.ticket_id
  where t.event_id=p_event_id
    and lower(s.token_secret)=lower(trim(p_token))
  for update;

  if v_checked is not null then
    return query
      select 'ALREADY_USED'::text,
        'This attendee is already checked in.'::text,
        v.attendee_type,v.attendee_name,v.relationship,v.main_participant_name,
        v.event_title,v.ticket_reference,v.checked_in_at
      from public.validate_attendee_ticket(p_event_id,p_token) as v;
    return;
  end if;

  update public.event_tickets
  set checked_in_at=clock_timestamp(), checked_in_by=auth.uid()
  where id=v_ticket_id
  returning checked_in_at into v_checked;

  return query
    select 'VALID'::text,
      'Attendee check-in recorded.'::text,
      v.attendee_type,v.attendee_name,v.relationship,v.main_participant_name,
      v.event_title,v.ticket_reference,v_checked
    from public.validate_attendee_ticket(p_event_id,p_token) as v;
end;
$function$;

