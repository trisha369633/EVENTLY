create or replace function public.validate_attendee_ticket(
  p_event_id bigint,
  p_token text
)
returns table (
  attendee_type text,
  attendee_name text,
  relationship text,
  main_participant_name text,
  event_title text,
  ticket_status text,
  ticket_reference text,
  checked_in_at timestamptz,
  registration_id bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_ticket record;
begin
  if auth.uid() is null then
    raise exception 'Sign in to validate tickets.' using errcode = '28000';
  end if;
  if not public.evently_ticket_is_super_admin()
    and not exists (
      select 1
      from public.user_roles as ur
      join public.event_volunteer_assignments as a
        on a.volunteer_user_id = ur.user_id
        and a.event_id = p_event_id
        and a.is_active
      where ur.user_id = auth.uid()
        and ur.role::text = 'volunteer'
    ) then
    raise exception 'You are not assigned to validate tickets for this event.'
      using errcode = '42501';
  end if;
  select t.*, r.full_name as main_name, r.registration_status,
    r.fee_amount, g.status as guest_status,
    e.title as event_title, e.status::text as event_status
  into v_ticket
  from public.event_ticket_secrets as s
  join public.event_tickets as t on t.id = s.ticket_id
  join public.event_registrations as r on r.id = t.registration_id
  join public.events as e on e.id = t.event_id
  left join public.event_guests as g on g.id = t.guest_id
  left join lateral (
    select ps.payment_status
    from public.event_payment_submissions as ps
    where ps.registration_id = r.id
    order by ps.submitted_at desc, ps.id desc
    limit 1
  ) as payment on true
  where t.event_id = p_event_id
    and lower(trim(s.token_secret)) = lower(trim(coalesce(p_token,'')))
    and lower(trim(coalesce(p_token,''))) ~ '^[0-9a-f]{64}$';

  if not found
    or v_ticket.ticket_status <> 'active'
    or v_ticket.registration_status <> 'registered'
    or v_ticket.event_status in ('cancelled','completed')
    or (v_ticket.attendee_type = 'guest' and v_ticket.guest_status <> 'registered')
  then
    return;
  end if;
  if v_ticket.fee_amount > 0 then
    if not exists (
      select 1
      from public.event_payment_submissions as ps
      where ps.registration_id = v_ticket.registration_id
        and ps.payment_status = 'approved'
    ) then
      return;
    end if;
  end if;

  return query
    select v_ticket.attendee_type,
      coalesce(v_ticket.attendee_name_snapshot,
        v_ticket.main_name),
      v_ticket.relationship_snapshot,
      v_ticket.main_name,
      v_ticket.event_title,
      v_ticket.ticket_status,
      v_ticket.ticket_reference,
      v_ticket.checked_in_at,
      v_ticket.registration_id;
end;
$function$;

