create or replace function public.register_event_with_guests(
  p_event_id bigint,
  p_full_name text,
  p_email text,
  p_phone text,
  p_participant_type text,
  p_institution_id bigint,
  p_department_id bigint,
  p_identity_number text,
  p_form_answers jsonb,
  p_guests jsonb default '[]'::jsonb
)
returns public.event_registrations
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_event public.events%rowtype;
  v_settings public.event_guest_settings%rowtype;
  v_registration public.event_registrations%rowtype;
  v_guest record;
  v_guest_count integer := 0;
  v_main_fee numeric;
  v_guest_fee numeric;
  v_total_fee numeric;
  v_registered_guests bigint;
begin
  if auth.uid() is null then
    raise exception 'Sign in to register.' using errcode = '28000';
  end if;
  if not exists (
    select 1
    from public.user_roles as ur
    where ur.user_id = auth.uid()
      and ur.role::text = 'participant'
  ) then
    raise exception 'Only participants can create event registrations.'
      using errcode = '42501';
  end if;
  if p_participant_type not in ('student','teacher','alumni') then
    raise exception 'Choose a valid participant type.' using errcode = '22023';
  end if;
  if coalesce(length(trim(p_full_name)),0) = 0
    or coalesce(length(trim(p_email)),0) = 0
    or coalesce(length(trim(p_phone)),0) = 0
    or coalesce(length(trim(p_identity_number)),0) = 0 then
    raise exception 'Main participant details are required.' using errcode = '22023';
  end if;

  select e.* into v_event
  from public.events as e
  where e.id = p_event_id
  for update;
  if not found
    or v_event.status::text <> 'published'
    or v_event.registration_deadline <= clock_timestamp()
  then
    raise exception 'Registration is closed.' using errcode = '22023';
  end if;
  if exists (
    select 1 from public.event_registrations as r
    where r.event_id = p_event_id
      and r.user_id = auth.uid()
  ) then
    raise exception 'You already have a registration for this event.'
      using errcode = '23505';
  end if;

  v_main_fee := case p_participant_type
    when 'student' then v_event.student_fee
    when 'teacher' then v_event.teacher_fee
    when 'alumni' then v_event.alumni_fee
  end;
  if v_main_fee is null or v_main_fee < 0 then
    raise exception 'The event participant fee is invalid.' using errcode = '22023';
  end if;

  select count(*)::integer into v_guest_count
  from jsonb_array_elements(coalesce(p_guests,'[]'::jsonb));

  select s.* into v_settings
  from public.event_guest_settings as s
  where s.event_id = p_event_id;

  if v_guest_count > 0
    and (not found or not v_settings.is_enabled) then
    raise exception 'Guest registration is disabled for this event.'
      using errcode = '22023';
  end if;
  if found and v_guest_count > v_settings.max_guests_per_participant then
    raise exception 'The participant guest limit has been reached.'
      using errcode = '22023';
  end if;
  if found then
    select count(*) into v_registered_guests
    from public.event_guests as g
    where g.event_id = p_event_id
      and g.status = 'registered';
    if v_registered_guests + v_guest_count > v_settings.total_guest_limit then
      raise exception 'The event guest admission limit has been reached.'
        using errcode = '22023';
    end if;
  end if;

  v_total_fee := v_main_fee;
  if v_guest_count > 0 then
    for v_guest in
      select *
      from jsonb_to_recordset(p_guests) as g(full_name text, relationship text)
    loop
      if coalesce(length(trim(v_guest.full_name)),0) = 0
        or v_guest.relationship not in (
          'father','mother','sister','brother','husband','wife','child'
        ) then
        raise exception 'Every guest needs a name and valid relationship.'
          using errcode = '22023';
      end if;
      select f.guest_fee into v_guest_fee
      from public.event_guest_relationship_fees as f
      where f.event_id = p_event_id
        and f.relationship = v_guest.relationship
        and f.is_active;
      if not found then
        raise exception 'This guest relationship is not enabled.'
          using errcode = '22023';
      end if;
      v_total_fee := v_total_fee + v_guest_fee;
    end loop;
  end if;

  insert into public.event_registrations (
    event_id, user_id, full_name, email, phone, participant_type,
    institution_id, department_id, identity_number, form_answers, fee_amount,
    main_fee_snapshot, guest_fee_total
  ) values (
    p_event_id, auth.uid(), trim(p_full_name), lower(trim(p_email)),
    trim(p_phone), p_participant_type::text,
    p_institution_id, p_department_id, trim(p_identity_number),
    coalesce(p_form_answers,'{}'::jsonb), v_total_fee,
    v_main_fee, greatest(v_total_fee - v_main_fee,0)
  )
  returning * into v_registration;
  update public.event_registrations
  set fee_amount = v_total_fee,
      main_fee_snapshot = v_main_fee,
      guest_fee_total = greatest(v_total_fee - v_main_fee,0)
  where id = v_registration.id
  returning * into v_registration;

  if v_guest_count > 0 then
    for v_guest in
      select *
      from jsonb_to_recordset(p_guests) as g(full_name text, relationship text)
    loop
      select f.guest_fee into v_guest_fee
      from public.event_guest_relationship_fees as f
      where f.event_id = p_event_id
        and f.relationship = v_guest.relationship
        and f.is_active;
      insert into public.event_guests (
        event_id, registration_id, full_name, relationship,
        fee_snapshot, status
      ) values (
        p_event_id, v_registration.id, trim(v_guest.full_name),
        v_guest.relationship, v_guest_fee, 'registered'
      );
    end loop;
  end if;

  return v_registration;
end;
$function$;

