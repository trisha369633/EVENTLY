create or replace function public.evently_issue_guest_ticket(p_guest_id bigint)
returns table (
  ticket_id uuid,
  ticket_reference text,
  ticket_token text,
  ticket_status text,
  issued_at timestamptz,
  checked_in_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_guest public.event_guests%rowtype;
  v_registration public.event_registrations%rowtype;
  v_event_status text;
  v_payment_status text;
  v_ticket_id uuid;
  v_ticket_reference text;
  v_ticket_token text;
  v_ticket_status text;
  v_issued_at timestamptz;
  v_checked_in_at timestamptz;
begin
  select g.* into v_guest
  from public.event_guests as g
  where g.id = p_guest_id
  for update;
  if not found or v_guest.status <> 'registered' then
    return;
  end if;
  select r.* into v_registration
  from public.event_registrations as r
  where r.id = v_guest.registration_id
  for share;
  if not found or v_registration.registration_status <> 'registered' then
    return;
  end if;
  select e.status::text into v_event_status
  from public.events as e
  where e.id = v_guest.event_id;
  if v_event_status in ('cancelled','completed') then
    return;
  end if;
  if v_registration.fee_amount > 0 then
    select p.payment_status into v_payment_status
    from public.event_payment_submissions as p
    where p.registration_id = v_registration.id
    order by p.submitted_at desc, p.id desc
    limit 1;
    if v_payment_status is distinct from 'approved' then
      return;
    end if;
  end if;

  select t.id, t.ticket_reference, t.ticket_status, t.issued_at, t.checked_in_at
  into v_ticket_id, v_ticket_reference, v_ticket_status, v_issued_at, v_checked_in_at
  from public.event_tickets as t
  where t.guest_id = p_guest_id
  for update;
  if found then
    if v_ticket_status = 'active' then
      select s.token_secret into v_ticket_token
      from public.event_ticket_secrets as s
      where s.ticket_id = v_ticket_id;
    end if;
    return query
      select v_ticket_id, v_ticket_reference, v_ticket_token, v_ticket_status,
        v_issued_at, v_checked_in_at;
    return;
  end if;

  v_ticket_token := lower(
    replace(pg_catalog.gen_random_uuid()::text,'-','')
    || replace(pg_catalog.gen_random_uuid()::text,'-','')
  );
  v_ticket_reference := 'EVT-G-' || upper(replace(pg_catalog.gen_random_uuid()::text,'-',''));
  insert into public.event_tickets (
    registration_id, event_id, participant_user_id, ticket_reference,
    attendee_type, guest_id, attendee_name_snapshot,
    relationship_snapshot, attendee_key
  ) values (
    v_guest.registration_id, v_guest.event_id, v_registration.user_id,
    v_ticket_reference, 'guest', v_guest.id, v_guest.full_name,
    v_guest.relationship, 'guest:' || v_guest.id::text
  )
  returning id, ticket_status, issued_at, checked_in_at
  into v_ticket_id, v_ticket_status, v_issued_at, v_checked_in_at;
  insert into public.event_ticket_secrets (ticket_id, token_secret)
  values (v_ticket_id, v_ticket_token);
  return query
    select v_ticket_id, v_ticket_reference, v_ticket_token, v_ticket_status,
      v_issued_at, v_checked_in_at;
end;
$function$;

