create or replace function public.evently_enforce_attendee_distribution_uniqueness()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_item public.event_distribution_items%rowtype;
  v_key text;
  v_received bigint;
  v_corrections bigint;
begin
  select i.* into v_item
  from public.event_distribution_items as i
  where i.id = new.distribution_item_id
  for update;

  v_key := coalesce(
    new.attendee_key,
    'participant:' || new.registration_id::text
  );
  new.attendee_key := v_key;
  if new.attendee_type = 'guest' and new.guest_id is not null then
    v_key := 'guest:' || new.guest_id::text;
    new.attendee_key := v_key;
  end if;

  select coalesce(sum(r.quantity),0) into v_received
  from public.event_distribution_records as r
  where r.distribution_item_id = new.distribution_item_id
    and r.attendee_key = new.attendee_key;

  select coalesce(sum(c.quantity),0) into v_corrections
  from public.event_distribution_corrections as c
  join public.event_distribution_records as r on r.id = c.distribution_record_id
  where r.distribution_item_id = new.distribution_item_id
    and r.attendee_key = new.attendee_key;

  if v_received - v_corrections + new.quantity > v_item.max_per_participant then
    raise exception 'This attendee has already reached the item limit.'
      using errcode = '23505';
  end if;
  return new;
end;
$function$;

